let myArray = [];
let cell = 64;
let counter = 1;
let row = [];

for (let i = 1; i <= cell; i++) {
  row.push(counter); // Add the current counter value to the row
  console.log(`row: ${row}`);
  counter++;
  console.log(`counter: ${counter}`);

  if (i % 8 === 0) {
    myArray.push(row); // Add the completed row to the grid
    row = []; // Reset row for the next batch
  }
}

